"""The migrations build exactly the schema the models describe (QA-21).

Twelve columns had a server default that a migration added (to back-fill
existing rows) but the model did not declare, so `alembic check` reported
drift and a future autogenerated migration would have dropped those defaults.
The models now declare them; this keeps it that way. PostgreSQL only — the
deployed database — on a scratch database of its own.
"""
from __future__ import annotations

from app.tests.test_mentor_one_active import PG, _alembic, needs_pg


@needs_pg
def test_migrations_and_models_describe_the_same_schema():
    from sqlalchemy import create_engine, text
    from sqlalchemy.engine import make_url

    from app.core.config import Settings
    base = make_url(Settings(DATABASE_URL=PG).sqlalchemy_url)
    scratch = base.set(database=f"{base.database}_schema")
    admin = create_engine(base.set(database="postgres"), isolation_level="AUTOCOMMIT")
    with admin.connect() as c:
        c.execute(text(f'DROP DATABASE IF EXISTS "{scratch.database}"'))
        c.execute(text(f'CREATE DATABASE "{scratch.database}"'))
    url = scratch.render_as_string(hide_password=False)
    try:
        upgrade = _alembic(url, "upgrade", "head")
        assert upgrade.returncode == 0, upgrade.stderr[-2000:]
        check = _alembic(url, "check")
        assert check.returncode == 0, check.stderr[-3000:]
        assert "No new upgrade operations detected" in check.stdout + check.stderr
    finally:
        with admin.connect() as c:
            c.execute(text(f'DROP DATABASE IF EXISTS "{scratch.database}"'))
        admin.dispose()
